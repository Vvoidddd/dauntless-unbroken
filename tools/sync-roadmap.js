// Regenerates docs/roadmap.md from ROADMAP.md, so the site never drifts from the checklist.
// Usage (from the repository root): node tools/sync-roadmap.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const source = fs.readFileSync(path.join(root, "ROADMAP.md"), "utf8").replace(/\r\n/g, "\n");

const repoUrl = "{{ site.github.repository_url }}";
const body = source
    .replace(/\]\((docs\/[^)]+\.md|NOTICE\.md|UPSTREAM\.md)\)/g, (_, target) => {
        const url = target.startsWith("docs/")
            ? "/dauntless-unbroken/" + target.slice(5).replace(/index\.md$/, "").replace(/\.md$/, ".html")
            : `${repoUrl}/blob/main/${target}`;
        return `](${url})`;
    })
    // The page title comes from the front matter.
    .replace(/^# .*\n+/, "")
    .replace(
        /^`docs\/roadmap\.md` is a copy of this file\..*$/m,
        `This page is generated from [\`ROADMAP.md\`](${repoUrl}/blob/main/ROADMAP.md), the checklist we work from.`
    )
    .trimEnd();

// Everything is literal text to Liquid, whatever braces the checklist contains, except the one repository link.
const literal = "{% raw %}\n" + body.split(repoUrl).join(`{% endraw %}${repoUrl}{% raw %}`) + "\n{% endraw %}";

// Search and social description (keep it 120-160 characters) and the language keys the docs use to pair
// English and Finnish pages (lang + ref, see docs/_includes/head_custom.html).
const description =
    "The Dauntless Unbroken roadmap: implemented launcher and server features, operating principles and ongoing in-game verification.";

const page = [
    "---",
    "title: Roadmap",
    "nav_order: 5",
    `description: ${JSON.stringify(description)}`,
    "lang: en",
    "ref: roadmap",
    "---",
    "",
    "<!-- Generated by tools/sync-roadmap.js from ROADMAP.md. Edit ROADMAP.md, then rerun the script. -->",
    "",
    "# Roadmap",
    "{: .no_toc }",
    "",
    "<details open markdown=\"block\">",
    "  <summary>Contents</summary>",
    "  {: .text-delta }",
    "1. TOC",
    "{:toc}",
    "</details>",
    "",
    literal,
    "",
].join("\n");

fs.writeFileSync(path.join(root, "docs", "roadmap.md"), page);
console.log(`docs/roadmap.md regenerated (${page.split("\n").length} lines)`);
